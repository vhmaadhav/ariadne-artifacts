#!/usr/bin/env python3
"""Evaluate canonical IRIS manifests with resumable, raw-pose predictions."""
from __future__ import annotations

import argparse
import csv
import json
import multiprocessing as mp
import os
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from driftsense.config import (
    SHIPPED_BAND, SHIPPED_STRIP_ROTATION, SHIPPED_SUBPIXEL_ROWS,
    SHIPPED_THRESHOLD, SHIPPED_VERIFICATION,
)

FIELDS = ["pair_id", "method", "found", "score", "x", "y", "theta",
          "scale", "seconds", "status"]
SHIPPED_KWARGS = dict(refine=True, verification=SHIPPED_VERIFICATION,
                      band=SHIPPED_BAND, subpixel_rows=SHIPPED_SUBPIXEL_ROWS,
                      strip_rot=SHIPPED_STRIP_ROTATION)
VARIANTS = {
    "shipped": ({}, "Shipped register.py decode."),
    "noexit": ({"auto_early_exit": False}, "Evaluate every pose hypothesis; ablation reference."),
    "k1": ({"hypotheses": 1}, "One pose hypothesis."),
    "k5": ({"hypotheses": 5}, "Five pose hypotheses."),
    "nocanon": ({"canonicalize": False}, "Original search frame and nominal network template."),
    "netselect": ({"verification": "network"}, "Select by network score; retain native stages."),
    "netnative": ({"verification": "network", "native_verification": False},
                  "Select and score by network; skip all native verification stages."),
    "nopolish": ({"polish": False}, "Skip pose polish and its nested strip rotation."),
    "nopscale": ({"polish_scale": False}, "Keep pre-polish scale; retain rotation polish."),
    "integer": ({"subpixel": "integer"}, "Integer ZNCC peaks; independent drift-row estimates remain enabled."),
    "norows": ({"subpixel_rows": False}, "Skip drift-row correction."),
    "nostrip": ({"strip_rot": False}, "Skip strip rotation."),
    "consensus": ({"verification": "consensus"}, "Rank/band agreement selects; otherwise native ZNCC."),
    "small": ({}, "Shipped decode with the small checkpoint."),
    "wide2": ({}, "Shipped decode with the alternate wide checkpoint."),
}
VARIANT_WEIGHTS = {
    "small": "weights/driftsense_pre_p6last_72.55.pt",
    "wide2": "weights/driftsense_wide.pt",
}
for _name, (_kwargs, _meaning) in VARIANTS.items():
    if _name not in {"shipped", "small", "wide2"}:
        _kwargs["auto_early_exit"] = False


def decode_kwargs(variant):
    return {**SHIPPED_KWARGS, **VARIANTS[variant][0]}


def variants_table():
    lines = ["| Variant | Exact kwargs and checkpoint | Meaning |",
             "| --- | --- | --- |"]
    for name, (_, meaning) in VARIANTS.items():
        kwargs = json.dumps(decode_kwargs(name), sort_keys=True)
        weights = VARIANT_WEIGHTS.get(name, "weights/driftsense.pt")
        lines.append(f"| {name} | `{kwargs}`; weights=`{weights}` | {meaning} |")
    return "\n".join(lines)


def write_variants():
    table = variants_table()
    target = ROOT / "results/iris/VARIANTS.md"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        "# IRIS variants\n\nGenerated by `scripts/iris_eval.py --list-variants`.\n\n"
        "Kwargs below are applied over locate_phase2 defaults. Every pair adds "
        "`label_convention` from its manifest row. `--weights` overrides the "
        "listed checkpoint; `--threshold` defaults to SHIPPED_THRESHOLD. "
        "Only shipped, small and wide2 retain automatic early exit.\n\n"
        + table + "\n", encoding="utf-8")
    return table


_MODEL = None
_MODEL_WEIGHTS = None


def _worker(job):
    """Cache a model per process, and bound torch/OpenCV threads there."""
    row, variant, weights, threads, threshold = job
    import torch
    torch.set_num_threads(threads)
    import cv2
    cv2.setNumThreads(threads)
    import infer
    from driftsense.matching import locate_phase2

    prediction = dict.fromkeys(FIELDS)
    prediction.update(pair_id=row["pair_id"], method=variant, found=0,
                      score=0, x=float("nan"), y=float("nan"),
                      theta=float("nan"), scale=float("nan"), seconds=0)
    started = None
    try:
        global _MODEL, _MODEL_WEIGHTS
        if _MODEL_WEIGHTS != weights:
            _MODEL = infer.load_model(weights)
            _MODEL_WEIGHTS = weights
        if _MODEL is None:
            raise RuntimeError(f"could not load learned model: {weights}")
        model, device = _MODEL
        reference = infer.read_gray(row["reference_path"])
        search = infer.read_gray(row["search_path"])
        kwargs = decode_kwargs(variant)
        kwargs["label_convention"] = row["label_convention"]
        started = time.perf_counter()
        res = locate_phase2(model, reference, search, device, **kwargs)
        prediction["seconds"] = time.perf_counter() - started
        started = None
        score = float(res.get("confidence", res.get("score")))
        prediction.update(found=int(score >= threshold), score=score,
                          x=res["x"], y=res["y"], theta=res["theta"],
                          scale=res["scale"], status="ok")
    except (Exception, SystemExit) as error:
        if started is not None:
            prediction["seconds"] = time.perf_counter() - started
        prediction["status"] = f"{type(error).__name__}: {error}"
    return prediction


def _read_predictions(path, variant):
    if not path.exists() or path.stat().st_size == 0:
        return []
    with path.open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        if reader.fieldnames != FIELDS:
            raise ValueError(f"prediction schema mismatch in {path}")
        rows = list(reader)
    if any(row["method"] != variant for row in rows):
        raise ValueError("resume output contains a different variant")
    ids = [row["pair_id"] for row in rows]
    if len(ids) != len(set(ids)):
        raise ValueError("resume output contains duplicate pair_id values")
    if any(None in row or any(value is None for value in row.values()) for row in rows):
        raise ValueError("resume output contains an incomplete CSV row")
    return rows


def run(args):
    with Path(args.manifest).open(newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        required = {"pair_id", "split", "reference_path", "search_path", "found",
                    "gt_x", "gt_y", "gt_scale", "gt_rot_deg", "label_convention",
                    "stratum", "group_id", "source"}
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(f"canonical manifest missing columns: {sorted(missing)}")
        rows = list(reader)
    ids = [row["pair_id"] for row in rows]
    if any(not pid for pid in ids) or len(ids) != len(set(ids)):
        raise ValueError("canonical pair_id must be nonempty and unique")
    # Limit is the first K manifest rows, before sorting or resume filtering.
    if args.limit is not None:
        rows = rows[:args.limit]
    output = Path(args.out)
    output.parent.mkdir(parents=True, exist_ok=True)
    previous = _read_predictions(output, args.variant)
    completed = {row["pair_id"] for row in previous}
    rows = sorted((row for row in rows if row["pair_id"] not in completed),
                  key=lambda row: row["pair_id"])
    weights = args.weights or VARIANT_WEIGHTS.get(args.variant, "weights/driftsense.pt")
    jobs = [(row, args.variant, weights, args.threads, args.threshold) for row in rows]
    print(f"{len(jobs)} pending pairs, {len(previous)} resumed; "
          f"variant={args.variant}, jobs={args.jobs}, threads={args.threads}", flush=True)
    with output.open("a", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=FIELDS)
        if handle.tell() == 0:
            writer.writeheader()
            handle.flush()
        if jobs:
            with mp.get_context("spawn").Pool(args.jobs) as pool:
                for i, prediction in enumerate(pool.imap(_worker, jobs, chunksize=1), 1):
                    writer.writerow(prediction)
                    handle.flush()
                    print(f"{i}/{len(jobs)} {prediction['pair_id']} "
                          f"{prediction['status']}", flush=True)
    # A resumed run can append IDs before older rows. Sort atomically at the end.
    predictions = _read_predictions(output, args.variant)
    if predictions != sorted(predictions, key=lambda row: row["pair_id"]):
        temporary = output.with_name(output.name + ".tmp")
        with temporary.open("w", newline="", encoding="utf-8") as handle:
            writer = csv.DictWriter(handle, fieldnames=FIELDS)
            writer.writeheader()
            writer.writerows(sorted(predictions, key=lambda row: row["pair_id"]))
        os.replace(temporary, output)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest")
    parser.add_argument("--variant", choices=VARIANTS, default="shipped")
    parser.add_argument("--out")
    parser.add_argument("--jobs", type=int, choices=range(1, 3), default=1)
    parser.add_argument("--threads", type=int, choices=range(1, 5), default=4)
    parser.add_argument("--limit", type=int)
    parser.add_argument("--weights")
    parser.add_argument("--threshold", type=float, default=SHIPPED_THRESHOLD)
    parser.add_argument("--list-variants", action="store_true")
    args = parser.parse_args(argv)
    table = write_variants()
    if args.list_variants:
        print(table)
        return
    if not args.manifest or not args.out:
        parser.error("--manifest and --out are required unless --list-variants is used")
    if args.limit is not None and args.limit < 0:
        parser.error("--limit must be nonnegative")
    run(args)


if __name__ == "__main__":
    main()
